-- =====================================================================
-- Futsal Manager - DDL + carga inicial (PostgreSQL 11+)
-- Crie o banco antes (PostgreSQL não aceita IF NOT EXISTS no CREATE DATABASE):
--     CREATE DATABASE futsal_db;
-- Depois conecte-se ao futsal_db e execute este script inteiro.
--
-- Modelagem:
--   competicao ........ tabela independente
--   tecnico  1:1 time . (time.id_tecnico UNIQUE)
--   time     1:N jogador
--   competicao 1:N jogo ; time 1:N jogo (casa e visitante)
--   usuario  1:N compra ; jogo 1:N compra
-- =====================================================================

DROP TABLE IF EXISTS compra, jogo, jogador, time, usuario, competicao, tecnico CASCADE;

-- Técnicos (1:1 com Time)
CREATE TABLE tecnico (
  id SERIAL PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(100),
  telefone VARCHAR(15),
  licenca VARCHAR(50),
  data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Competições (tabela independente)
CREATE TABLE competicao (
  id SERIAL PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  descricao TEXT,
  data_inicio DATE,
  data_fim DATE,
  local VARCHAR(100),
  data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Times (1:1 com Técnico, 1:N com Jogador) - logo guarda o caminho da imagem
CREATE TABLE time (
  id SERIAL PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  cidade VARCHAR(100),
  id_tecnico INTEGER UNIQUE REFERENCES tecnico(id) ON DELETE SET NULL,
  logo VARCHAR(255),
  data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Jogadores (N:1 com Time) - foto guarda o caminho da imagem
CREATE TABLE jogador (
  id SERIAL PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  numero INTEGER NOT NULL,
  posicao VARCHAR(50),
  id_time INTEGER REFERENCES time(id) ON DELETE CASCADE,
  data_nascimento DATE,
  foto VARCHAR(255),
  data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Usuários do sistema (login). perfil: 'admin' (administração) ou 'cliente'
CREATE TABLE usuario (
  id SERIAL PRIMARY KEY,
  nome VARCHAR(100) NOT NULL,
  email VARCHAR(100) NOT NULL UNIQUE,
  senha_hash VARCHAR(64) NOT NULL,
  perfil VARCHAR(10) NOT NULL DEFAULT 'cliente' CHECK (perfil IN ('admin', 'cliente')),
  data_criacao TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- Partidas à venda (N:1 com Competição e com os dois Times)
CREATE TABLE jogo (
  id SERIAL PRIMARY KEY,
  id_competicao INTEGER NOT NULL REFERENCES competicao(id),
  id_time_casa INTEGER NOT NULL REFERENCES time(id),
  id_time_visitante INTEGER NOT NULL REFERENCES time(id),
  data_hora TIMESTAMP NOT NULL,
  local VARCHAR(100),
  preco NUMERIC(8,2) NOT NULL CHECK (preco >= 0),
  capacidade INTEGER NOT NULL CHECK (capacidade > 0),
  CHECK (id_time_casa <> id_time_visitante)
);

-- Compras de ingressos (núcleo do sistema). Pagamento simulado.
CREATE TABLE compra (
  id SERIAL PRIMARY KEY,
  id_usuario INTEGER NOT NULL REFERENCES usuario(id),
  id_jogo INTEGER NOT NULL REFERENCES jogo(id),
  quantidade INTEGER NOT NULL CHECK (quantidade BETWEEN 1 AND 6),
  valor_total NUMERIC(10,2) NOT NULL,
  forma_pagamento VARCHAR(10) NOT NULL CHECK (forma_pagamento IN ('PIX', 'CARTAO', 'BOLETO')),
  status VARCHAR(10) NOT NULL DEFAULT 'PAGO' CHECK (status IN ('PAGO', 'CANCELADO')),
  data_compra TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

